import pandas as pd

# Load dataset into a DataFrame
df = pd.read_csv("data.csv")

# Display first and last few rows
print("First 5 rows:")
print(df.head())

print("\nLast 5 rows:")
print(df.tail())

# Check data types and general information
print("\nDataset Information:")
df.info()

# Display column names
print("\nColumns in the dataset:")
print(df.columns)

# Summary statistics
print("\nSummary Statistics:")
print(df.describe(include='all'))

# Handle missing values (only numeric columns)
numeric_cols = df.select_dtypes(include='number').columns
df[numeric_cols] = df[numeric_cols].fillna(df[numeric_cols].mean())

# ------------------------------
# Replace the column names below
# with the actual names in your dataset
# ------------------------------

# Example column names
existing_column = "existing_column"
another_column = "another_column"
category_column = "category_column"
numeric_column = "numeric_column"

# Create a new column
if existing_column in df.columns:
    df["new_column"] = df[existing_column] * 2

    # Create a Series and perform operations
    series = df[existing_column]
    print("\nSeries + 10:")
    print(series + 10)

# Filter rows based on conditions
if existing_column in df.columns and another_column in df.columns:
    filtered_df = df[
        (df[existing_column] > 50) &
        (df[another_column] < 100)
    ]
    print("\nFiltered DataFrame:")
    print(filtered_df)

# Grouping and aggregation
if category_column in df.columns and numeric_column in df.columns:
    grouped = df.groupby(category_column)[numeric_column].mean()
    print("\nGrouped Mean:")
    print(grouped)

# Sorting
if numeric_column in df.columns:
    df_sorted = df.sort_values(by=numeric_column, ascending=False)
    print("\nSorted DataFrame:")
    print(df_sorted)

    # Boolean masking
    masked_df = df[df[numeric_column] > df[numeric_column].median()]
    print("\nMasked DataFrame:")
    print(masked_df)

# Remove duplicates
df.drop_duplicates(inplace=True)

# Drop rows with missing values
df.dropna(inplace=True)

# Select first two columns as a subset
subset_df = df.iloc[:, :2]

# Save the new DataFrame
subset_df.to_csv("filtered_data.csv", index=False)

# Compute summary statistics
if numeric_column in df.columns:
    print("\nTotal Sum:", df[numeric_column].sum())
    print("Mean:", df[numeric_column].mean())
    print("Standard Deviation:", df[numeric_column].std())

